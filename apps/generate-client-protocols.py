"""Generate both native clients' exact protocol registry from the shared catalog.

The optional blog target receives only its generated public protocol registry.
No SDK, application, network, credential, research directory or release bundle
is used. Existing article and publication data are never read or rewritten.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts'))
from protocol_codec import Codec, canonical


PUBLIC_FAMILIES = (
    'paper-tag-catalog', 'paper-tag-flat-tags', 'paper-tag-selection',
    'paper-tag-catalog-snapshot', 'paper-tag-catalog-versions',
    'researcher-workbench', 'researcher-sidecars', 'paper-research-context',
    'paper-search-index-manifest', 'paper-citation-source',
)


def rendered_sources(blog_repo=None):
    source = ROOT / 'config/protocols/clients.json'
    # Native-only domains may evolve independently; server/workflow catalogs
    # are deliberately excluded from both app binaries and the public registry.
    sources = [source, *sorted(source.parent.glob('clients-*.json'))]
    originals = [(item, item.read_bytes()) for item in sources]
    catalogs = [json.loads(raw) for _path, raw in originals]
    codec = Codec(catalogs)
    entries = {}
    for row in [row for catalog in catalogs for row in catalog['protocols']]:
        name = row['name']
        formats = [{'tag': name, 'fp': codec.schema_fingerprint(name),
                    'variant': row['currentVariant'],
                    'header': codec.record_header(name, name),
                    'schema': row['currentSchema'], 'historical': False}]
        for item in row['historical']:
            fingerprint = item.get('header', {}).get('schemaFingerprint')
            formats.append({'tag': item['tag'], 'fp': fingerprint,
                            'variant': item['variant'],
                            'header': codec.record_header(item['tag'], name, fingerprint),
                            'schema': item.get('schema'), 'historical': True})
        dependencies = {
            'paperdigest-cloud-transfer': {'snapshotFormat': 'paperdigest-cloud-snapshot'},
            'paper-research-context': {'citationFormat': 'researcher-sidecars', 'workbenchFormat': 'researcher-workbench'},
            'paper-tag-flat-tags': {'selectionFormat': 'paper-tag-selection'},
            'paperdigest-retained-capture-export-proof': {'historyFormat': 'paperdigest-retained-capture-export-history'},
            'paperdigest-zotero-web': {'planFormat': 'paperdigest-zotero-plan'},
            'android-study-input': {'identityFormat': 'android-study'},
            'paperdigest-mac-study-input': {'identityFormat': 'paperdigest-mac-study-identity'},
            'paperdigest-mac-study-identity': {'extractorFormat': 'paperdigest-mac-pdf-extractor'},
        }.get(name, {})
        for descriptor in formats:
            if descriptor['fp'] is not None:
                for field, dependency in dependencies.items():
                    if not codec.has_valid_header(descriptor['schema'].get(field), dependency):
                        raise ValueError(f'{name} original schema must bind its exact registered {field}')
        # This index is for writing current headers only. Readers select the
        # exact original tag/fingerprint pair from formats, never this map.
        headers = {name: formats[0]['header']}
        entries[name] = {
            'currentVariant': row['currentVariant'],
            'schemaFingerprint': codec.schema_fingerprint(name),
            'formats': formats,
            'headers': headers,
        }
    data = canonical(entries)
    digest = (hashlib.sha256(originals[0][1]).hexdigest() if len(originals)==1 else
              hashlib.sha256(canonical([{'file':item.name,'sha256':hashlib.sha256(raw).hexdigest()}
                                        for item,raw in originals]).encode('utf-8')).hexdigest())
    swift = ('// Generated by apps/generate-client-protocols.py; do not edit.\n'
             'import Foundation\n\n'
             'enum GeneratedClientProtocols {\n'
             f'    static let catalogSHA256 = "{digest}"\n'
             f'    static let json = #"""\n{data}\n"""#\n'
             '}\n')
    # JVM constants have a 65,535-byte modified-UTF-8 limit. Chunk the actual
    # JSON before escaping Kotlin interpolation; do not split an escape token.
    kotlin_chunks = [data[index:index + 8000].replace('$', "${'$'}")
                     for index in range(0, len(data), 8000)]
    kotlin_data = ',\n        '.join('"""' + chunk + '"""' for chunk in kotlin_chunks)
    kotlin = ('// Generated by apps/generate-client-protocols.py; do not edit.\n'
              'package com.nanless.paperdigest.protocols\n\n'
              'internal object GeneratedClientProtocols {\n'
              f'    const val catalogSHA256 = "{digest}"\n'
              f'    val json = listOf({kotlin_data}).joinToString("")\n'
              '}\n')
    outputs = {
        ROOT / 'apps/macos/Sources/ClientProtocolRegistry.generated.swift': swift,
        ROOT / ('apps/android/app/src/main/java/com/nanless/paperdigest/'
                'protocols/ClientProtocolRegistry.generated.kt'): kotlin,
    }
    public = {name: entries[name] for name in PUBLIC_FAMILIES}
    template = (ROOT / 'apps/public-protocol-api.js').read_text()
    export = 'module.exports = createPublicProtocolApi;'
    if template.count(export) != 1:
        raise ValueError('Public protocol runtime export does not match the generator')
    runtime = template.replace(export, '')
    javascript = ('// Generated from the shared project protocol catalog; do not edit.\n'
                  '(function(root,factory){\n'
                  '  const api=factory();\n'
                  '  if(typeof module===\'object\'&&module.exports)module.exports=api;\n'
                  '  else root.PaperDigestProtocols=api;\n'
                  '})(typeof globalThis!==\'undefined\'?globalThis:this,function(){\n'
                  + runtime + '\nreturn createPublicProtocolApi(' + canonical(public) + ');\n});\n')
    outputs[ROOT / 'apps/macos/Resources/website-tags/protocol-registry.js'] = javascript
    bridge = {name: entries[name] for name in ('published-aggregate-document', 'reader-source-notice-snapshot')}
    outputs[ROOT / 'apps/macos/Resources/native-bridge-protocols.js'] = (
        '// Generated from the native bridge protocol catalog; do not edit.\n'
        + runtime + '\nexport const NativeBridgeProtocols = createPublicProtocolApi('
        + canonical(bridge) + ');\n')
    if blog_repo is not None:
        outputs[blog_repo / 'assets/js/protocol-registry.js'] = javascript
        # This is the actual canonical public table's byte hash, not the hash
        # of private native-only declarations. Extending a private app format
        # must not silently revise an already frozen website consumer bundle.
        public_digest = hashlib.sha256(canonical(public).encode('utf-8')).hexdigest()
        outputs[blog_repo / 'data/paperdigest-protocols.json'] = (canonical({'catalogSHA256': public_digest, 'families': public}) + '\n')
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='read-only exact generated-source check')
    parser.add_argument('--blog-repo', type=Path, help='explicit blog checkout for public registry generation/check')
    args = parser.parse_args()
    blog_repo = args.blog_repo.resolve(strict=True) if args.blog_repo is not None else None
    if blog_repo is not None and not (blog_repo / '.git').exists():
        raise ValueError('The explicit blog target must be a real Git checkout')
    for path, expected in rendered_sources(blog_repo).items():
        if path.is_symlink():
            raise ValueError(f'Generated registry cannot be a symlink: {path}')
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f'Protocol registry is stale: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_text() != expected:
                path.write_text(expected)
    print('Client protocol registries match the shared catalog.' if args.check
          else 'Generated both native client protocol registries.')


if __name__ == '__main__':
    main()
